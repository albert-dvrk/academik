import re


class PostgresConnection:
    """Shared queries use SQLite placeholders and named rows."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, parameters=()):
        return self.connection.execute(sql.replace("?", "%s"), parameters)

    def executemany(self, sql, parameters):
        with self.connection.cursor() as cursor:
            cursor.executemany(sql.replace("?", "%s"), parameters)

    def create_schema(self, tables):
        tables = re.sub(r"id INTEGER PRIMARY KEY,", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,", tables)
        tables = tables.replace("INTEGER NOT NULL REFERENCES", "BIGINT NOT NULL REFERENCES")
        tables = tables.replace("INTEGER PRIMARY KEY REFERENCES", "BIGINT PRIMARY KEY REFERENCES")
        tables = tables.replace("BLOB", "BYTEA").replace("expires INTEGER", "expires BIGINT")
        tables = tables.replace("occurred_at INTEGER", "occurred_at BIGINT")
        self.connection.execute(tables)
        self.connection.execute("""
            CREATE OR REPLACE FUNCTION record_request_status() RETURNS trigger AS $$
            BEGIN
                IF TG_OP = 'INSERT' THEN
                    INSERT INTO request_events(request_id,status,occurred_at)
                    VALUES (NEW.id, NEW.status, EXTRACT(EPOCH FROM clock_timestamp())::BIGINT);
                ELSIF OLD.status <> NEW.status THEN
                    INSERT INTO request_events(request_id,status,occurred_at)
                    VALUES (NEW.id, NEW.status, EXTRACT(EPOCH FROM clock_timestamp())::BIGINT);
                END IF;
                RETURN NEW;
            END;
            $$ LANGUAGE plpgsql;
            CREATE OR REPLACE TRIGGER request_status_events AFTER INSERT OR UPDATE OF status ON requests
            FOR EACH ROW EXECUTE FUNCTION record_request_status();
        """)
